#!/usr/bin/env python3
"""Derive the ABI manifest/header/export lists from maintained CMotive declarations.

This intentionally supports this project's explicit scalar/pointer method grammar;
unsupported declarations fail instead of silently omitting a method.
"""
from pathlib import Path
import argparse,json,re,sys
ROOT=Path(__file__).resolve().parents[1]
TYPE={'I32':'int32_t','U32':'uint32_t','I64':'int64_t','U64':'uint64_t','Uchar':'uint8_t','Void':'void'}
def ctype(t):return ctype(t[:-1])+'*' if t.endswith('*') else TYPE[t]
def outputs():
    api=[]; classes=[]
    pattern=re.compile(r'^(I32|U32|I64|U64|Uchar|Void\*?)\n(\w+)\n((?:\w+ : [\w*]+\n)*)\(\)\n\{',re.M)
    for path in sorted((ROOT/'include/CMotiveAndObjective').glob('*.HMOT')):
        s=path.read_text(); m=re.search(r'^Class\s+(\w+)\s*\{',s,re.M)
        if not m or m[1]!=path.stem:raise ValueError('Class/file mismatch: '+str(path))
        cls=m[1]; classes.append(cls); methods=[]
        for m in pattern.finditer(s):
            params=[tuple(x.strip() for x in line.split(':')) for line in m[3].splitlines()]
            a={'cls':cls,'name':m[2],'returns':m[1],'params':params}
            ctype(a['returns'])
            for n,t in params:ctype(t)
            methods.append(a)
        if not methods:raise ValueError('No recognized methods in '+str(path))
        if len({a['name'] for a in methods})!=len(methods):raise ValueError('Unsupported overload')
        api+=methods
    exports=[]
    h='/* Generated from CMotive declarations. BSL-1.0. See docs/API.md. */\n#ifndef CMO_H\n#define CMO_H\n#include <stdint.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\n'
    for c in classes:
        prefix='CMotiveAndObjective__'+c
        h+='void* '+prefix+'__new(void);\nvoid '+prefix+'__delete(void* instance);\n'
        exports.extend([prefix+'__new',prefix+'__delete'])
    for a in api:
        name='CMotiveAndObjective__'+a['cls']+'__'+a['name'];exports.append(name)
        h+=ctype(a['returns'])+' '+name+'(void* instance'+''.join(', '+ctype(t)+' '+n for n,t in a['params'])+');\n'
    h+='#ifdef __cplusplus\n}\n#endif\n#endif\n'
    signatures='# Public method signatures\n\nGenerated from .HMOT declarations. Contracts are in [API.md](API.md).\n\n'
    for c in classes:
        signatures+='## '+c+'\n\n'+''.join('`'+a['returns']+' '+a['name']+'('+', '.join(n+': '+t for n,t in a['params'])+')`  \n' for a in api if a['cls']==c)+'\n'
    return {
        'api.json':json.dumps(api,indent=2)+'\n',
        'build-support/headers.mk':'# Generated by tools/sync_api.py\n'+''.join(var+' = '+' '.join(x.relative_to(ROOT).as_posix() for x in files)+'\n' for var,files in [
            ('cmo_public_headers',sorted((ROOT/'include/CMotiveAndObjective').glob('*.HMOT'))),
            ('cmo_internal_headers',sorted((ROOT/'include/CMotiveAndObjective/Internal').glob('*.HMOT'))),
            ('cmo_header_files',sorted((ROOT/'include/CMotiveAndObjective').rglob('*.HMOT')))]),
        'include/CMotiveAndObjective.h':h,
        'src/CMotiveAndObjective.CMOT':'// Unified CMotive compilation unit. BSL-1.0.\n'+''.join('#include "CMotiveAndObjective/'+c+'.HMOT"\n' for c in classes),
        'build-support/exports.map':'CMotiveAndObjective_1_0 {\n global:\n'+''.join('  '+e+';\n' for e in exports)+' local: *;\n};\n',
        'build-support/exports.def':'LIBRARY "CMotiveAndObjective-1.0.0.dll"\nEXPORTS\n'+'\n'.join(exports)+'\n',
        'build-support/exports.macos':''.join('_'+e+'\n' for e in exports),
        'build-support/exported-symbols.txt':'\n'.join(exports)+'\n',
        'docs/API-SIGNATURES.md':signatures,
    },len(classes),len(api)
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    files,classes,methods=outputs();stale=[]
    for name,text in files.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text:stale.append(name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    if stale:raise SystemExit('Generated API files are stale: '+', '.join(stale))
    print(f'API {"checked" if args.check else "updated"}: {classes} classes, {methods} methods')
if __name__=='__main__':main()
